export function manualById(id: string) {
  return MANUAL.find((s) => s.id === id);
}

/** 지금 화면(언어 경로를 뗀 경로)을 설명하는 글 */
export function manualForPath(localPath: string) {
  return MANUAL.filter((s) => s.paths?.some((re) => re.test(localPath)));
}
